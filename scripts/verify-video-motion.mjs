import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://localhost:4324';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
const errors=[];
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.heroOpacity=[];let i=0;const run=()=>{const h=document.querySelector('#hero-title');if(h)window.heroOpacity.push(getComputedStyle(h).opacity);if(++i<80)requestAnimationFrame(run)};requestAnimationFrame(run)});
 await page.goto(base);
 await page.waitForFunction(()=>{const v=document.querySelector('.hero-visual video');return v&&v.currentTime>.1&&!v.paused});
 const hero=page.locator('.hero-visual video');
 assert.equal(await hero.evaluate(v=>v.videoWidth),1080);
 assert.equal(await hero.evaluate(v=>v.muted),true);
 assert.equal(await hero.evaluate(v=>v.loop),false);
 assert.equal(await page.locator('.selected-projects video').first().getAttribute('src'),null);
 assert.ok(await page.evaluate(()=>window.heroOpacity.every(opacity=>opacity==='1')));
 await page.locator('[data-motion-toggle]').click();assert.equal(await hero.evaluate(v=>v.paused),true);
 const paused=await hero.evaluate(v=>v.currentTime);await page.waitForTimeout(200);assert.equal(await hero.evaluate(v=>v.currentTime),paused);
 await page.locator('[data-motion-toggle]').click();await page.waitForFunction(()=>!document.querySelector('.hero-visual video').paused);
 await page.locator('#selection').scrollIntoViewIfNeeded();await page.waitForFunction(()=>document.querySelector('.hero-visual video').paused);
 await page.goto(base+'/projects/habitat-de-a-a-z/');
 await page.locator('.detail-hero').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelector('.detail-hero video')?.currentTime>.1);
 await page.locator('.language-switch a[lang="fr"]').click();await page.waitForURL('**/fr/projets/habitat-de-a-a-z/');
 await page.locator('.detail-hero').scrollIntoViewIfNeeded();await page.waitForFunction(()=>document.querySelector('.detail-hero video')?.currentTime>.1);
 assert.equal(await page.locator('.depth-active').count(),0);
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForFunction(()=>[...document.querySelectorAll('video')].every(v=>v.paused));
 assert.equal(await page.locator('[data-motion-toggle]').isVisible(),false);
 assert.equal(await page.locator('.animated-visual[data-video-ready]').count(),0);
 await page.goto(base);
 assert.equal(await hero.getAttribute('src'),null);
 await page.emulateMedia({reducedMotion:'no-preference'});await page.waitForFunction(()=>document.querySelector('.hero-visual video').currentTime>.1);
 await page.waitForFunction(()=>document.querySelector('.hero-visual video').ended,{},{timeout:12000});
 const finalTime=await hero.evaluate(v=>v.currentTime);await page.waitForTimeout(250);assert.equal(await hero.evaluate(v=>v.currentTime),finalTime);
 assert.equal(await page.locator('.hero-visual .animated-visual').getAttribute('data-video-ready'),'');
 await page.locator('[data-motion-toggle]').click();await page.waitForFunction(()=>{const v=document.querySelector('.hero-visual video');return !v.paused&&v.currentTime<2});
 await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/tmp/emma-video-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'/tmp/emma-video-desktop.png'});
 await context.close();
 const plain=await browser.newContext({javaScriptEnabled:false});const noJS=await plain.newPage();await noJS.goto(base);
 assert.equal(await noJS.locator('.hero-visual img').isVisible(),true);assert.equal(await noJS.locator('.hero-visual video').getAttribute('src'),null);assert.equal(await noJS.locator('[data-motion-toggle]').isVisible(),false);await plain.close();
 assert.deepEqual(errors,[]);
 console.log('PASS: real 1080px video, deferred loading, pause/resume/replay, offscreen pause, final-frame hold, EN/FR navigation, reduced motion, mobile and no-JS fallback; no hero opacity flash.');
}finally{await browser.close()}
